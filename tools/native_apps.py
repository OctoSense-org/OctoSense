# --- Marked blocks ---------------------------------------------------------


def begin_marker(name):
    return f"# BEGIN native-apps: {name} {NOTE}"


def end_marker(name):
    return f"# END native-apps: {name}"


def replace_blocks(text, blocks, label):
    """`text` with each named block's lines between its markers replaced."""
    lines = text.split("\n")
    for name, body in blocks.items():
        begin, end = begin_marker(name), end_marker(name)
        starts = [i for i, line in enumerate(lines) if line.strip() == begin]
        ends = [i for i, line in enumerate(lines) if line.strip() == end]
        if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
            raise ManifestError(f"{label}: needs exactly one '{begin}' ... '{end}' block")
        lines[starts[0] + 1:ends[0]] = body
    marked = re.findall(r"^\s*# BEGIN native-apps: (.*?) \(generated", text, re.M)
    for name in marked:
        if name not in blocks:
            raise ManifestError(f"{label}: block '{name}' has no source in {MANIFEST} (remove its markers)")
    return "\n".join(lines)


def workspace_pins(text):
    """(crate, git, rev) of each git pin in [workspace.dependencies]."""
    pins, table = [], None
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            table = stripped
            continue
        if table != "[workspace.dependencies]":
            continue
        match = re.match(r"([A-Za-z0-9_-]+)\s*=\s*\{(.*)\}", stripped)
        if not match:
            continue
        git = re.search(r'\bgit\s*=\s*"([^"]+)"', match.group(2))
        rev = re.search(r'\brev\s*=\s*"([^"]+)"', match.group(2))
        if git and rev:
            pins.append((match.group(1), git.group(1), rev.group(1)))
    return pins


def check_one_revision(apps, text):
    """Each git repository an app comes from is pinned at one revision."""
    problems = []
    for app in apps:
        source = app["source"]
        if "git" not in source or "tag" in source:
            continue
        for crate, git, rev in workspace_pins(text):
            if same_git(git, source["git"]) and rev != source["rev"]:
                problems.append(f"{crate} pins {git} at {rev[:12]}, {app['id']} at {source['rev'][:12]}")
    if problems:
        raise ManifestError("Cargo.toml: one revision per repository:\n  " + "\n  ".join(sorted(set(problems))))


def generate(root):
    """{relative path: (current text or None, generated text)}."""
    root = Path(root)
    apps = load(root)

    def read(rel):
        path = root / rel
        return path.read_text() if path.is_file() else None

    out = {}
    text = read("Cargo.toml")
    if text is None:
        raise ManifestError("Cargo.toml is missing")
    new = replace_blocks(text, root_blocks(apps), "Cargo.toml")
    check_one_revision(apps, new)
    out["Cargo.toml"] = (text, new)
    rel = "crates/shell/Cargo.toml"
    text = read(rel)
    if text is None:
        raise ManifestError(f"{rel} is missing")
    out[rel] = (text, replace_blocks(text, shell_blocks(apps), rel))
    text = read(PROCESS_APPS)
    if text is None:
        raise ManifestError(f"{PROCESS_APPS} is missing")
    out[PROCESS_APPS] = (text, replace_blocks(text, process_blocks(apps), PROCESS_APPS))
    for shell, rel in PACKAGES.items():
        text = read(rel)
        if text is None:
            raise ManifestError(f"{rel} is missing")
        out[rel] = (text, replace_blocks(text, package_block(apps, shell, text), rel))
    out[RUST_FILE] = (read(RUST_FILE), render_rust(apps))
    out[AGENTS_FILE] = (read(AGENTS_FILE), render_agents(apps))
    return out


def check_tagged_locks(root, apps):
    """A tag-pinned app's Cargo.lock entry names the manifest's commit.

    Cargo records `git+<url>?tag=<tag>#<commit>`; a tag moved after review
    shows up here as a different commit."""
    lock = Path(root) / "Cargo.lock"
    if not lock.is_file():
        return []
    text, problems = lock.read_text(), []
    for app in apps:
        source = app["source"]
        if "tag" not in source:
            continue
        pattern = re.compile(r'name = "%s"\nversion = "[^"]*"\nsource = "git\+([^"?#]+)\?tag=([^"#]+)#([0-9a-f]{40})"' % re.escape(app["crate"]))
        found = [m for m in pattern.finditer(text) if same_git(m.group(1), source["git"])]
        if not found:
            problems.append(f"Cargo.lock has no {app['crate']} from {source['git']} at tag {source['tag']}; run python3 tools/native_apps.py")
        for m in found:
            if m.group(2) != source["tag"] or m.group(3) != source["rev"]:
                problems.append(f"Cargo.lock: {app['crate']} {m.group(2)} is {m.group(3)[:12]}, native-apps.json says {source['tag']} is {source['rev'][:12]} (a moved tag?)")
    return problems


DESKTOP_CATALOG = "desktop/config/apps.json"
DESKTOP_TARGETS = ("macos", "windows", "linux")


def catalog_problems(root, apps):
    """The desktop catalog's rows for native apps agree with the manifest.

    A process launch builds `crate` and runs `bin` from native-apps.json
    (`clients::launch_plan`); the catalog row only names and places the app.
    So a row that says another package, binary or source would only
    mislead, and an app that runs as a process on a desktop needs a row."""
    path = Path(root) / DESKTOP_CATALOG
    if not path.is_file():
        return [f"{DESKTOP_CATALOG} is missing"]
    try:
        rows = json.loads(path.read_text())
    except json.JSONDecodeError as error:
        return [f"{DESKTOP_CATALOG}: {error}"]
    by_id = {row.get("id"): row for row in rows if isinstance(row, dict)}
    problems = []
    for app in apps:
        ident = app["id"]
        row = by_id.get(ident)
        process = any(app["hosting"][target] != "module" for target in DESKTOP_TARGETS)
        if row is None:
            if process:
                problems.append(f"{DESKTOP_CATALOG} has no row for {ident}, which runs as a process on a desktop")
            continue
        if not app["bin"]:
            problems.append(f"{DESKTOP_CATALOG}: {ident} has a row but no bin in {MANIFEST}: it has no process form")
            continue
        if row.get("package") != app["crate"]:
            problems.append(f"{DESKTOP_CATALOG}: {ident}'s package is {row.get('package')!r}, {MANIFEST} says {app['crate']!r}")
        if row.get("bin") != app["bin"]:
            problems.append(f"{DESKTOP_CATALOG}: {ident}'s bin is {row.get('bin')!r}, {MANIFEST} says {app['bin']!r}")
        source = app["source"]
        if "path" in source:
            want = (Path(root) / source["path"] / "Cargo.toml").resolve()
            got = row.get("manifest")
            if got is None or (path.parent / got).resolve() != want:
                problems.append(f"{DESKTOP_CATALOG}: {ident}'s manifest should be {source['path']}/Cargo.toml, as {MANIFEST} says")
        elif str(source.get("local") or "").startswith(".sources/makepad/"):
            if row.get("source") != "makepad":
                problems.append(f"{DESKTOP_CATALOG}: {ident} comes from Makepad in {MANIFEST}; its row should say \"source\": \"makepad\"")
        else:
            problems.append(f"{DESKTOP_CATALOG}: {ident}'s source in {MANIFEST} has no catalog form")
    return problems


def changed_pins(old, new):
    """Crates whose pin in [workspace.dependencies] changed (not added)."""
    def pins(text):
        found, table = {}, None
        for line in text.splitlines():
            stripped = line.strip()
            if stripped.startswith("["):
                table = stripped
                continue
            match = re.match(r"([A-Za-z0-9_-]+)\s*=", stripped)
            if table == "[workspace.dependencies]" and match:
                found[match.group(1)] = stripped
        return found
    before, after = pins(old), pins(new)
    return sorted(c for c in before if c in after and before[c] != after[c])


def update_lock(root, crates, cargo="cargo"):
    for crate in crates:
        note(f"cargo update -p {crate}")
        subprocess.run([cargo, "update", "-p", crate], cwd=root, check=True)
    note("cargo metadata (settles Cargo.lock)")
    subprocess.run([cargo, "metadata", "--format-version", "1"], cwd=root, check=True, stdout=subprocess.DEVNULL)


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 when a generated place drifted")
    parser.add_argument("--no-lock", action="store_true", help="do not run cargo to update Cargo.lock")
    args = parser.parse_args(argv)
    try:
        results = generate(root)
    except ManifestError as error:
        print(f"native-apps: {error}", file=sys.stderr)
        return 2
    drifted = [rel for rel, (old, new) in results.items() if old != new]
    if args.check:
        for rel in drifted:
            print(f"::error::{rel} is not what native-apps.json generates; run python3 tools/native_apps.py")
        lock_problems = check_tagged_locks(root, load(root)) + catalog_problems(root, load(root))
        for problem in lock_problems:
            print(f"::error::{problem}")
        if not drifted and not lock_problems:
            note("every generated place matches native-apps.json")
        return 1 if drifted or lock_problems else 0
    catalog = catalog_problems(root, load(root))
    for problem in catalog:
        print(f"::error::{problem}")
    for rel in drifted:
        (Path(root) / rel).write_text(results[rel][1])
        note(f"wrote {rel}")
    if not drifted:
        note("nothing to do")
    toml_changed = any(rel.endswith("Cargo.toml") for rel in drifted)
    if toml_changed and not args.no_lock:
        old, new = results["Cargo.toml"]
        update_lock(root, changed_pins(old, new))
    return 1 if catalog else 0


if __name__ == "__main__":
    sys.exit(main())
