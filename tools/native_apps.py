class ManifestError(Exception):
    pass


def note(message):
    print(f"native-apps: {message}", file=sys.stderr)


# --- The manifest ----------------------------------------------------------


def load(root):
    path = Path(root) / MANIFEST
    try:
        data = json.loads(path.read_text())
    except (OSError, ValueError) as error:
        raise ManifestError(f"{MANIFEST}: {error}")
    return validate(data)


def validate(data):
    """The apps, checked; every problem is reported at once."""
    problems = []
    if not isinstance(data, dict) or data.get("schema") != 1 or not isinstance(data.get("apps"), list):
        raise ManifestError(f'{MANIFEST}: expected {{"schema": 1, "apps": [...]}}')
    seen, features, crates = set(), set(), set()
    for index, app in enumerate(data["apps"]):
        where = f"apps[{index}]"
        if not isinstance(app, dict):
            problems.append(f"{where}: not an object")
            continue
        where = f"{app.get('id', where)}"
        missing = sorted(REQUIRED_KEYS - set(app))
        unknown = sorted(set(app) - APP_KEYS)
        if missing:
            problems.append(f"{where}: missing {', '.join(missing)}")
        if unknown:
            problems.append(f"{where}: unknown {', '.join(unknown)}")
        if missing:
            continue
        ident = app["id"]
        if not isinstance(ident, str) or not re.fullmatch(r"[a-z][a-z0-9-]*", ident):
            problems.append(f"{where}: id must be lowercase letters, digits and '-'")
        if ident in seen:
            problems.append(f"{where}: duplicate id")
        seen.add(ident)
        feature = feature_of(app)
        if feature in features:
            problems.append(f"{where}: duplicate feature {feature}")
        features.add(feature)
        if app["crate"] in crates:
            problems.append(f"{where}: duplicate crate {app['crate']}")
        crates.add(app["crate"])
        source = app["source"]
        if not isinstance(source, dict):
            problems.append(f"{where}: source must be an object")
        elif "path" in source:
            if set(source) != {"path"}:
                problems.append(f"{where}: a path source has only 'path'")
        elif set(source) not in ({"git", "rev", "local"}, {"git", "tag", "rev", "local"}):
            problems.append(f"{where}: source is {{git, rev, local}}, {{git, tag, rev, local}} or {{path}}")
        elif not re.fullmatch(r"[0-9a-f]{40}", str(source["rev"])):
            problems.append(f"{where}: source.rev must be a full commit id (for a tag: the commit it names)")
        elif "tag" in source and not re.fullmatch(RELEASE_TAG, str(source["tag"])):
            problems.append(f"{where}: source.tag must be a release tag vX.Y.Z or vX.Y.Z-rc.N")
        if isinstance(source, dict) and ident in TAGGED_RELEASES and "tag" not in source:
            problems.append(f"{where}: is taken only as a tagged release (hagency-org/Rinx#37): pin source.tag, not a raw rev")
        if not modules_of(app) or not all(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(::[A-Za-z_][A-Za-z0-9_]*)+", m) for m in modules_of(app)):
            problems.append(f"{where}: module must be a Rust path (or a list of them)")
        if app["bin"] is not None and not (isinstance(app["bin"], str) and app["bin"]):
            problems.append(f"{where}: bin must be a binary name or null")
        bin_features = app.get("bin_features", [])
        if not isinstance(bin_features, list) or not all(isinstance(x, str) for x in bin_features):
            problems.append(f"{where}: bin_features must be a list of strings")
        elif bin_features and not app["bin"]:
            problems.append(f"{where}: bin_features without a bin")
        if not isinstance(app["default_features"], bool):
            problems.append(f"{where}: default_features must be true or false")
        for key in ("crate_features", "implies"):
            if not isinstance(app[key], list) or not all(isinstance(x, str) for x in app[key]):
                problems.append(f"{where}: {key} must be a list of strings")
        hosting = app["hosting"]
        if not isinstance(hosting, dict):
            problems.append(f"{where}: hosting must be an object")
        else:
            for target in TARGETS:
                if target not in hosting:
                    problems.append(f"{where}: hosting.{target} is missing")
            for target, value in hosting.items():
                if target not in TARGETS + ("wasm",):
                    problems.append(f"{where}: hosting.{target}: unknown target")
                elif value not in HOSTINGS:
                    problems.append(f"{where}: hosting.{target}: {value!r} is not one of {', '.join(HOSTINGS)}")
                elif value != "module" and target in MODULE_ONLY:
                    problems.append(f"{where}: hosting.{target}: {target} has no processes; only 'module'")
                elif value == "process" and target == "linux":
                    problems.append(f"{where}: hosting.linux: 'process' would run without Vulkan+Wayland; "
                                    "use 'process-if-vulkan' (ADR 0004 §2)")
                elif value != "module" and not app["bin"]:
                    problems.append(f"{where}: hosting.{target}: '{value}' needs a bin")
        shells = app["shells"]
        if not isinstance(shells, dict) or set(shells) != set(PACKAGES):
            problems.append(f"{where}: shells must name {', '.join(PACKAGES)}")
        else:
            for shell, value in shells.items():
                if value not in SHELL_LINKS:
                    problems.append(f"{where}: shells.{shell}: {value!r} is not one of {', '.join(SHELL_LINKS)}")
        if app["native_mobile"] not in ("always", "feature"):
            problems.append(f"{where}: native_mobile must be 'always' or 'feature'")
        for key in ("sandbox", "storage", "agent"):
            if not isinstance(app[key], dict):
                problems.append(f"{where}: {key} must be an object")
        if isinstance(app["sandbox"], dict):
            problems += [f"{where}: {p}" for p in sandbox_problems(app["sandbox"])]
        if isinstance(app["storage"], dict):
            problems += [f"{where}: {p}" for p in storage_problems(app["storage"])]
        if isinstance(app["agent"], dict) and not isinstance(app["agent"].get("octos"), list):
            problems.append(f"{where}: agent.octos must be a list")
        if isinstance(app["agent"], dict):
            problems += [f"{where}: {p}" for p in tool_policy_problems(app["agent"].get("tool_policy", {}))]
            problems += [f"{where}: {p}" for p in agent_problems(ident, app["agent"])]
    problems += grant_problems([a for a in data["apps"] if isinstance(a, dict) and isinstance(a.get("agent"), dict)])
    if problems:
        raise ManifestError(f"{MANIFEST}:\n  " + "\n  ".join(problems))
    return data["apps"]


NETWORKS = ("none", "any")
EXTERNAL_ROOTS = ("home", "documents", "downloads", "desktop", "pictures", "music", "movies", "tmp")


def sandbox_problems(sandbox):
    """`sandbox`: {"network": "none"|"any", "processes": bool} (ADR 0004 §3):
    what a process-hosted instance's OS sandbox allows beyond its files."""
    problems = []
    if set(sandbox) != {"network", "processes"}:
        problems.append("sandbox needs exactly network and processes")
    if sandbox.get("network") not in NETWORKS:
        problems.append(f"sandbox.network must be one of {', '.join(NETWORKS)}")
    if not isinstance(sandbox.get("processes"), bool):
        problems.append("sandbox.processes must be true or false")
    return problems


STORAGE_KEYS = ("max_bytes", "accounts", "agent_workspace", "cache_max_bytes", "external")


def storage_problems(storage):
    """`storage` (ADR 0004 §11), the block the shell parses with
    `app_storage::StorageSpec` at startup: `accounts` a bool, `agent_workspace`
    "account" or "none", the optional byte ceilings positive whole numbers,
    `external` a list of `<root>[/<path>]:ro|rw` grants outside the jail
    (part of the sandbox, never of an agent's workspace). Unknown fields are
    refused, as the shell refuses them."""
    problems = []
    unknown = sorted(set(storage) - set(STORAGE_KEYS))
    if unknown:
        problems.append(f"storage.{unknown[0]} is not a storage field (one of {', '.join(STORAGE_KEYS)})")
    if not isinstance(storage.get("accounts"), bool):
        problems.append("storage.accounts must be true or false")
    if storage.get("agent_workspace", "account") not in ("account", "none"):
        problems.append("storage.agent_workspace must be 'account' or 'none'")
    for key in ("max_bytes", "cache_max_bytes"):
        value = storage.get(key)
        if value is not None and (isinstance(value, bool) or not isinstance(value, int) or value <= 0):
            problems.append(f"storage.{key} must be a positive whole number of bytes")
    external = storage.get("external")
    if not isinstance(external, list):
        return problems + ["storage.external must be a list"]
    for grant in external:
        match = isinstance(grant, str) and re.fullmatch(r"([a-z]+)(/[A-Za-z0-9._/-]+)?:(ro|rw)", grant)
        if not match or match.group(1) not in EXTERNAL_ROOTS or ".." in grant:
            problems.append(f"storage.external: {grant!r} is not <root>[/<path>]:ro|rw with root one of {', '.join(EXTERNAL_ROOTS)}")
    return problems


def tool_policy_problems(policy):
    """`agent.tool_policy`: {tool: {"confirm": "host"|"app", "auto_approvable": bool}}
    (ADR 0004 §8). A tool the shell confirms live and no standing rule may
    approve is `confirm: host`, `auto_approvable: false`."""
    if not isinstance(policy, dict):
        return ["agent.tool_policy must be an object"]
    problems = []
    for tool, rule in policy.items():
        if not re.fullmatch(r"[a-z][a-z0-9_]*", tool):
            problems.append(f"agent.tool_policy: {tool!r} is not a tool name")
        elif not isinstance(rule, dict) or set(rule) != {"confirm", "auto_approvable"}:
            problems.append(f"agent.tool_policy.{tool}: needs exactly confirm and auto_approvable")
        elif rule["confirm"] not in ("host", "app"):
            problems.append(f"agent.tool_policy.{tool}.confirm must be 'host' or 'app'")
        elif not isinstance(rule["auto_approvable"], bool):
            problems.append(f"agent.tool_policy.{tool}.auto_approvable must be true or false")
    return problems


AGENT_KEYS = {"octos", "tools", "generic_tools", "grants", "tool_policy", "budget"}
# The fields a `tools.json` entry may carry (octos `ToolDecl`, UPCR-2026-035);
# `app` is the shell's to set.
DECL_FIELDS = {"name", "description", "input_schema", "output_schema", "risk", "background", "outward", "confirm", "shareable"}
RISKS = ("read", "act", "destructive")
# octos's own shell: never granted to an app agent (ADR 0004 §12); command
# execution is a host tool (`terminal.run`) with a live approval.
OCTOS_SHELL = ("shell", "bash", "exec_command", "write_stdin", "group:runtime")


def agent_problems(ident, agent):
    """The agent block (ADR 0004 §1, §7, §12): `octos` (its `octos.*`
    services), `tools` (null, or its own `tools.json` entries, named
    `<id>.<tool>`), `generic_tools` (the exact octos kernel tools its agent
    gets; never octos's shell), `grants` (other apps' shareable tools,
    `{"app", "tool"}`), `budget` (`calls_per_turn`, `calls_per_day`)."""
    problems = []
    unknown = sorted(set(agent) - AGENT_KEYS)
    if unknown:
        problems.append(f"agent: unknown {', '.join(unknown)}")
    tools = agent.get("tools")
    names = []
    if tools is not None:
        if not isinstance(tools, list) or not tools:
            problems.append("agent.tools must be null or a non-empty list of tools.json entries")
            tools = []
        for i, tool in enumerate(tools):
            where = f"agent.tools[{i}]"
            if not isinstance(tool, dict):
                problems.append(f"{where}: not an object")
                continue
            extra = sorted(set(tool) - DECL_FIELDS)
            if extra:
                problems.append(f"{where}: unknown {', '.join(extra)} (the kernel refuses them)")
            name = tool.get("name")
            if not isinstance(name, str) or not re.fullmatch(rf"{re.escape(ident)}(\.[a-z][a-z0-9_]*)+", name):
                problems.append(f"{where}: name must be {ident}.<tool>")
            elif name in names:
                problems.append(f"{where}: {name} is declared twice")
            else:
                names.append(name)
            if not isinstance(tool.get("description"), str) or not tool["description"].strip():
                problems.append(f"{where}: description is required")
            schema = tool.get("input_schema")
            if not isinstance(schema, dict) or schema.get("type") != "object":
                problems.append(f"{where}: input_schema must describe an object")
            if "output_schema" in tool and not isinstance(tool["output_schema"], dict):
                problems.append(f"{where}: output_schema must be a schema object")
            if tool.get("risk") not in RISKS:
                problems.append(f"{where}: risk must be one of {', '.join(RISKS)}")
            if tool.get("confirm", "host") not in ("host", "app"):
                problems.append(f"{where}: confirm must be 'host' or 'app'")
            for flag in ("shareable", "background", "outward"):
                if flag in tool and not isinstance(tool[flag], bool):
                    problems.append(f"{where}: {flag} must be true or false")
    policy = agent.get("tool_policy", {})
    if isinstance(policy, dict) and tools is not None:
        short = {n.split(".", 1)[1] for n in names}
        for rule in policy:
            if rule not in short:
                problems.append(f"agent.tool_policy.{rule}: {ident} declares no tool {ident}.{rule}")
    generic = agent.get("generic_tools", [])
    if not isinstance(generic, list):
        problems.append("agent.generic_tools must be a list of octos tool names")
        generic = []
    for g in generic:
        if g in OCTOS_SHELL:
            problems.append(f"agent.generic_tools: {g} is octos's own shell, which no app agent gets "
                            "(ADR 0004 §12: command execution is a host tool)")
        elif not (isinstance(g, str) and re.fullmatch(r"[A-Za-z0-9_-]{1,64}", g)):
            problems.append(f"agent.generic_tools: {g!r} is not an octos tool name")
    if len(set(map(str, generic))) != len(generic):
        problems.append("agent.generic_tools names a tool twice")
    budget = agent.get("budget")
    if budget is not None:
        if not isinstance(budget, dict) or not set(budget) <= {"calls_per_turn", "calls_per_day"}:
            problems.append("agent.budget is {calls_per_turn?, calls_per_day?}")
        else:
            for key, value in budget.items():
                if not isinstance(value, int) or isinstance(value, bool) or value < 1:
                    problems.append(f"agent.budget.{key} must be a positive integer")
    grants = agent.get("grants", [])
    if not isinstance(grants, list) or not all(isinstance(g, dict) and set(g) == {"app", "tool"}
                                               and all(isinstance(g[k], str) for k in g) for g in grants):
        problems.append('agent.grants must be a list of {"app": <owning app>, "tool": <its tool>}')
    return problems


def grant_problems(apps):
    """Each cross-app grant names another app's shareable tool: a native
    owner's tool must be in its `agent.tools` and `shareable`; a script
    owner (`os.*`) is checked when App Hub loads its `tools.json`."""
    problems = []
    declared = {a.get("id"): {t.get("name"): t for t in (a["agent"].get("tools") or []) if isinstance(t, dict)} for a in apps}
    for app in apps:
        grants = app["agent"].get("grants", [])
        if not isinstance(grants, list):
            continue
        for grant in grants:
            if not isinstance(grant, dict) or set(grant) != {"app", "tool"}:
                continue
            owner, tool = grant["app"], grant["tool"]
            where = f"{app.get('id')}: agent.grants {owner}/{tool}"
            if owner == app.get("id"):
                problems.append(f"{where}: an app's own tools need no grant")
            elif owner in declared:
                entry = declared[owner].get(tool)
                if entry is None:
                    problems.append(f"{where}: {owner} declares no {tool}")
                elif entry.get("shareable") is not True:
                    problems.append(f"{where}: {tool} is not shareable")
            elif not (isinstance(owner, str) and owner.startswith("os.")):
                problems.append(f"{where}: no native app {owner}, and not a system app (os.*)")
    return problems


def feature_of(app):
    return app.get("feature") or f"app-{app['id']}"


def modules_of(app):
    module = app["module"]
    if isinstance(module, str):
        return [module]
    if isinstance(module, list) and all(isinstance(m, str) for m in module):
        return module
    return []


def same_git(a, b):
    def norm(url):
        url = url.strip().rstrip("/")
        return (url[:-4] if url.endswith(".git") else url).lower()
    return norm(a) == norm(b)


# --- Rendering -------------------------------------------------------------


def s(value):
    """A TOML basic string (JSON's escaping is a subset of TOML's)."""
    return json.dumps(value)


def toml_list(values):
    return "[" + ", ".join(s(v) for v in values) + "]"


def pin_line(app):
    source = app["source"]
    if "path" in source:
        fields = [f"path = {s(source['path'])}"]
    else:
        pin = f"tag = {s(source['tag'])}" if "tag" in source else f"rev = {s(source['rev'])}"
        fields = [f"git = {s(source['git'])}", pin]
    if not app["default_features"]:
        fields.append("default-features = false")
    if app["crate_features"]:
        fields.append(f"features = {toml_list(app['crate_features'])}")
    return f"{app['crate']} = {{ {', '.join(fields)} }}"


def patch_urls(apps):
    """The git sources some app resolves to a local checkout, in order."""
    urls = []
    for app in apps:
        source = app["source"]
        if source.get("local") and not any(same_git(u, source["git"]) for u in urls):
            urls.append(source["git"])
    return urls


def root_blocks(apps):
    blocks = {"pins": [pin_line(app) for app in apps]}
    for url in patch_urls(apps):
        blocks[f"patch {url}"] = [
            f"{app['crate']} = {{ path = {s(app['source']['local'])} }}"
            for app in apps
            if app["source"].get("local") and same_git(app["source"]["git"], url)
        ]
    return blocks


def in_mobile_apps(app):
    return app["shells"]["phone"] in ("default", "mobile-apps")


def shell_blocks(apps):
    def dep(app, optional):
        fields = ["workspace = true"]
        if app["crate_features"]:
            fields.append(f"features = {toml_list(app['crate_features'])}")
        if optional:
            fields.append("optional = true")
        return f"{app['crate']} = {{ {', '.join(fields)} }}"

    mobile_apps = [feature_of(app) for app in apps if in_mobile_apps(app)] + BASE_DEFAULT
    features = [f"mobile-apps = {toml_list(mobile_apps)}"]
    features += [f"{feature_of(app)} = {toml_list(['dep:' + app['crate']] + app['implies'])}" for app in apps]
    return {
        "deps": [dep(app, True) for app in apps],
        "mobile deps": [dep(app, False) for app in apps if app["native_mobile"] == "always"],
        "features": features,
    }


def process_blocks(apps):
    """`crates/process-apps/Cargo.toml`: every app with a `bin`, with the
    features its binary needs, as a process launch builds it."""
    deps = []
    for app in apps:
        if not app["bin"]:
            continue
        features = app["crate_features"] + [f for f in app.get("bin_features", []) if f not in app["crate_features"]]
        fields = ["workspace = true"] + ([f"features = {toml_list(features)}"] if features else [])
        deps.append(f"{app['crate']} = {{ {', '.join(fields)} }}")
    return {"process deps": deps}


def optional_deps(cargo_toml):
    """The optional dependencies a package's own [dependencies] declares."""
    names, table = set(), None
    for line in cargo_toml.splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            table = stripped
            continue
        if table == "[dependencies]":
            match = re.match(r"([A-Za-z0-9_-]+)\s*=\s*\{(.*)\}", stripped)
            if match and re.search(r"\boptional\s*=\s*true\b", match.group(2)):
                names.add(match.group(1))
    return names


def package_block(apps, shell, cargo_toml):
    """A package's default and forwarded features. An app whose crate the
    package also depends on itself (optionally) turns that dependency on."""
    own = optional_deps(cargo_toml)
    linked = [app for app in apps if app["shells"][shell] != "off"]
    default = BASE_DEFAULT + SHELL_BASE_DEFAULT.get(shell, []) + [feature_of(app) for app in linked if app["shells"][shell] == "default"]
    mobile = [feature_of(app) for app in linked if in_mobile_apps(app) and app["crate"] in own]
    lines = [f"default = {toml_list(default)}",
             f"mobile-apps = {toml_list(mobile + ['octosense-shell/mobile-apps'])}"]
    for app in linked:
        deps = [f"dep:{app['crate']}"] if app["crate"] in own else []
        lines.append(f"{feature_of(app)} = {toml_list(deps + ['octosense-shell/' + feature_of(app)])}")
    return {"features": lines}


def rust_raw(text):
    """A Rust raw string literal holding `text`."""
    if '"#' in text:
        raise ManifestError(f"cannot embed {text!r} in a raw string")
    return f'r#"{text}"#'


def rust_hosting(value):
    return {"module": "Hosting::Module", "process": "Hosting::Process",
            "process-if-vulkan": "Hosting::ProcessIfVulkan"}[value]


